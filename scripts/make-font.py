#!/usr/bin/env python3
"""Builds lib/platform_desktop/src/platform/desktop/PixelFontData.cpp, the small
bitmap font the desktop screen window uses for text.

    python3 scripts/make-font.py [path/to/DejaVuSansMono-Bold.ttf]

Needs Pillow (pip install pillow). The output is checked in, so this only needs
running again to change the font.

The device draws text with M5GFX's own fonts, so this only affects the laptop
window. Each character is 7 pixels wide and 12 tall, covering printable ASCII
(space to ~). Anything else is drawn as a box.

The letters are traced from DejaVu Sans Mono Bold. Its licence allows this as long
as the copyright notice comes with it and the result isn't called Bitstream Vera
or DejaVu, so the notice is copied into the output.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
OUT = os.path.join(os.path.dirname(__file__), "..", "lib", "platform_desktop", "src", "platform", "desktop",
                   "PixelFontData.cpp")

POINT_SIZE = 11
WIDTH = 7
HEIGHT = 12
TOP_OFFSET = 2  # DejaVu leaves two empty rows above the tallest letters at this size

font = ImageFont.truetype(FONT, POINT_SIZE)

lines = [
    "// Generated by scripts/make-font.py. Don't edit by hand.",
    "//",
    "// Letter shapes traced from DejaVu Sans Mono Bold.",
    "// Bitstream Vera Fonts Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved.",
    "// Bitstream Vera is a trademark of Bitstream, Inc.",
    "// DejaVu changes are in the public domain.",
    "// Licence: https://dejavu-fonts.github.io/License.html",
    "",
    '#include "platform/desktop/PixelFont.h"',
    "",
    "namespace fvb {",
    "namespace pixelfont {",
    "",
    "// One row per byte, top row first. Bit 6 is the leftmost pixel.",
    "const uint8_t kGlyphs[kLast - kFirst + 1][kHeight] = {",
]

for code in range(32, 127):
    image = Image.new("1", (WIDTH, HEIGHT), 0)
    ImageDraw.Draw(image).text((0, -TOP_OFFSET), chr(code), font=font, fill=1)
    rows = []
    for y in range(HEIGHT):
        bits = 0
        for x in range(WIDTH):
            if image.getpixel((x, y)):
                bits |= 1 << (WIDTH - 1 - x)
        rows.append("0x%02x" % bits)
    shown = chr(code).replace("\\", "backslash")
    lines.append("    {%s},  // %s" % (", ".join(rows), shown if code != 32 else "space"))

lines += [
    "};",
    "",
    "}  // namespace pixelfont",
    "}  // namespace fvb",
    "",
]

with open(OUT, "w") as f:
    f.write("\n".join(lines))
print("Wrote", os.path.normpath(OUT))
